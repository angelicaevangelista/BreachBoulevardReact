begin;

-- The educational SQL/XSS simulations do not use this application database.
create table if not exists public.breach_access_codes (
  id bigint generated by default as identity primary key,
  code text not null unique check (length(code) between 1 and 128),
  created_at timestamptz not null default now(),
  expires_at timestamptz not null default (now() + interval '1 day')
);

create index if not exists breach_access_codes_expiration_idx
  on public.breach_access_codes (expires_at);
create index if not exists breach_access_codes_created_idx
  on public.breach_access_codes (created_at desc, id desc);

alter table public.breach_access_codes enable row level security;
revoke all on table public.breach_access_codes from public, anon, authenticated;
grant select, insert, delete on table public.breach_access_codes to service_role;
revoke all on sequence public.breach_access_codes_id_seq from public, anon, authenticated;
grant usage, select on sequence public.breach_access_codes_id_seq to service_role;

-- Parameterized comparison and database time preserve the access-code workflow.
create or replace function public.bb_validate_access_code(
  p_code text,
  p_check_expiration boolean default true
)
returns boolean
language sql
stable
security invoker
set search_path = ''
as $$
  select exists (
    select 1 from public.breach_access_codes
    where code = p_code and (not p_check_expiration or expires_at > now())
  );
$$;

create or replace function public.bb_cleanup_expired_codes()
returns integer
language plpgsql
security invoker
set search_path = ''
as $$
declare
  removed integer;
begin
  delete from public.breach_access_codes where expires_at <= now();
  get diagnostics removed = row_count;
  return removed;
end;
$$;

revoke all on function public.bb_validate_access_code(text, boolean) from public, anon, authenticated;
revoke all on function public.bb_cleanup_expired_codes() from public, anon, authenticated;
grant execute on function public.bb_validate_access_code(text, boolean) to service_role;
grant execute on function public.bb_cleanup_expired_codes() to service_role;

comment on table public.breach_access_codes is
  'Breach Boulevard access codes; server-only access through the PHP API.';

commit;
